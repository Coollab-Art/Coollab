// Resolved file names per slug, generated by demo-projects-plugin.js at build time.
let imagesMap = {}
try {
  imagesMap = require("../../.docusaurus/demo-projects-plugin/images.json")
} catch (e) {
  // Missing before the plugin has run for the first time (e.g. after `docusaurus clear`).
}

const THUMBNAILS_DIR = "/img/demo-project-thumbnails"

function thumbnail(project) {
  const file = imagesMap[project.slug]?.thumbnail
  return `${THUMBNAILS_DIR}/${file ?? `${project.slug}.png`}`
}

function image(project) {
  const file = imagesMap[project.slug]?.image
  return `${THUMBNAILS_DIR}/${file ?? `${project.slug}.png`}`
}

function download(project) {
  return `/demo-projects/${project.slug}.coollab`
}

